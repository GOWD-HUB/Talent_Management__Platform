# ==========================================================

def get_next_skill(
    roadmap,
    completed_skills,
):

    for level_name, skills in roadmap[
        "levels"
    ].items():

        for skill in skills:

            if (
                skill["skill"]
                not in completed_skills
            ):

                return {
                    "level": level_name,
                    **skill,
                }

    return None