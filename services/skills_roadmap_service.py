# ==========================================================
# GET ROADMAP
# ==========================================================

def get_roadmap(career_area):

    if not career_area:
        return DEFAULT_ROADMAP

    return ROADMAPS.get(
        career_area,
        DEFAULT_ROADMAP,
    )


# ==========================================================
# GET ALL SKILLS
# ==========================================================

def get_all_skills(roadmap):

    result = []

    for level_name, skills in roadmap[
        "levels"
    ].items():

        for skill in skills:

            result.append(
                {
                    "level": level_name,
                    **skill,
                }
            )

    return result


# ==========================================================
# CALCULATE PROGRESS
# ==========================================================

def calculate_progress(
    roadmap,
    completed_skills,
):

    all_skills = get_all_skills(
        roadmap
    )

    if not all_skills:
        return 0

    completed = 0

    for item in all_skills:

        if item["skill"] in completed_skills:
            completed += 1

    return round(
        completed
        / len(all_skills)
        * 100
    )


