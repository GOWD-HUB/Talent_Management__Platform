# ==========================================================
# NORMALIZE TEXT
# ==========================================================

def normalize_text(value):

    if value is None:
        return ""

    return str(value).lower().strip()


# ==========================================================
# MATCH CATEGORY
# ==========================================================

def calculate_category_match(
    category,
    profile,
):

    score = 20

    reasons = []

    interests = normalize_text(
        profile.get("interests")
    )

    favourite_subjects = normalize_text(
        profile.get("favourite_subjects")
    )

    dream_career = normalize_text(
        profile.get("dream_career")
    )

    skills = normalize_text(
        profile.get("skills")
    )


    # ======================================================
    # INTEREST MATCH
    # ======================================================

    interest_match_count = 0

    for keyword in category["keywords"]:

        if keyword.lower() in interests:

            interest_match_count += 1


    if interest_match_count > 0:

        score += min(
            35,
            interest_match_count * 10,
        )

        reasons.append(
            "Matches your interests"
        )


    # ======================================================
    # SUBJECT MATCH
    # ======================================================

    subject_match_count = 0

    for subject in category["subjects"]:

        if subject.lower() in favourite_subjects:

            subject_match_count += 1


    if subject_match_count > 0:

        score += min(
            30,
            subject_match_count * 10,
        )

        reasons.append(
            "Matches subjects you enjoy"
        )


    # ======================================================
    # DREAM CAREER MATCH
    # ======================================================

    if dream_career:

        for career in category["careers"]:

            career_title = normalize_text(
                career["title"]
            )

            if (
                dream_career in career_title
                or career_title in dream_career
            ):

                score += 15

                reasons.append(
                    "Includes your dream career"
                )

                break


    # ======================================================
    # SKILLS SIGNAL
    # ======================================================

    if skills:

        score += 5


    # ======================================================
    # FINAL SCORE
    # ======================================================

    score = min(
        score,
        95,
    )


    if not reasons:

        reasons.append(
            "A career area worth exploring"
        )


    return {
        **category,
        "match_score": score,
        "reasons": reasons,
    }


# ==========================================================
# RECOMMEND CATEGORIES
# ==========================================================

def recommend_categories(profile):

    results = []


    for category in CAREER_AREAS:

        result = calculate_category_match(
            category,
            profile,
        )

        results.append(
            result
        )


    results.sort(
        key=lambda item: item["match_score"],
        reverse=True,
    )


    return results