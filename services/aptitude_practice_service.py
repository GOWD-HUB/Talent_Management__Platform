def get_categories():
    return list(QUESTION_BANK.keys())


def get_questions(category):
    return QUESTION_BANK.get(category, [])


def calculate_score(questions, answers):
    correct = 0

    for index, question in enumerate(questions):
        selected = answers.get(index)

        if selected == question["answer"]:
            correct += 1

    total = len(questions)
    percentage = round(correct / total * 100) if total else 0

    return {
        "correct": correct,
        "total": total,
        "percentage": percentage,
    }


def performance_label(percentage):
    if percentage >= 85:
        return "Excellent"
    if percentage >= 70:
        return "Very Good"
    if percentage >= 55:
        return "Good"
    if percentage >= 40:
        return "Needs Practice"
    return "Needs Stronger Basics"


def recommendation(category, percentage):
    if percentage >= 85:
        return (
            f"Excellent work in {category}. Move to timed practice and harder mixed questions."
        )

    if percentage >= 70:
        return (
            f"Good performance in {category}. Review incorrect answers and practise another set."
        )

    if percentage >= 55:
        return (
            f"Your basics in {category} are developing well. Focus on weak question types and practise daily."
        )

    if percentage >= 40:
        return (
            f"Spend more time on {category} fundamentals before attempting harder questions."
        )

    return (
        f"Start with the basic concepts in {category}, solve easy examples first, "
        "and retry this practice after revision."
    )
